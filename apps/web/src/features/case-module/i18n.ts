export function toCyrillic(input: string) {
  return input.replace(/[OGog][‘ʻ’']|[Ss][Hh]|[Cc][Hh]|[Yy][AaOoUu]|[A-Za-z]|[‘ʻ’']/g, (part) => {
    const lower = part.toLowerCase();
    const value =
      lower.startsWith('o') && part.length > 1
        ? 'ў'
        : lower.startsWith('g') && part.length > 1
          ? 'ғ'
          : (({ sh: 'ш', ch: 'ч', ya: 'я', yo: 'ё', yu: 'ю' } as Record<string, string>)[lower] ??
            letters[lower] ??
            'ъ');
    return part[0] === part[0]?.toUpperCase()
      ? value.charAt(0).toUpperCase() + value.slice(1)
      : value;
  });
}
